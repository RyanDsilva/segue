#!/usr/bin/env swift
// Generates the Segue "Taped setlist" app icon from the geometry in docs/brand.md section 4.
//
// Writes (all under design/icon/):
//   layers/{background,sheet,tape}.svg   the three Liquid Glass layers
//   master.svg, master-light.svg         flat composites (dark/default, light)
//   icon-32.svg, icon-16.svg             hand-tuned small-size variants
//   Segue.icon/                          Icon Composer document
//   previews/*.png                       renders for review
//
// Usage: scripts/gen-icon.swift [--no-previews]   regenerate (and render previews)
//        scripts/gen-icon.swift --check           exit 1 if the checked-in files are stale
// The SVGs and Segue.icon are deterministic; previews are rendered with Icon Composer's
// `ictool` (Liquid Glass renditions) and AppKit (flat SVGs) and are for humans only.

import AppKit
import Foundation

// MARK: - Palette (brand.md sections 4 and 5)

enum Palette {
    static let ink = "#111113"
    static let paper = "#FFFFFF"
    static let lightGround = "#F2F2F4"
    static let lineGrey = "#9A9AA2"
    static let lineGreyLight = "#8A8A92"
    static let cue = "#F2555A"
}

// MARK: - Geometry (100 x 100 grid)

struct Box {
    let x: Double
    let y: Double
    let width: Double
    let height: Double
    let radius: Double
    let fill: String

    var svg: String {
        "<rect x=\"\(fmt(x))\" y=\"\(fmt(y))\" width=\"\(fmt(width))\" height=\"\(fmt(height))\""
            + " rx=\"\(fmt(radius))\" fill=\"\(fill)\"/>"
    }
}

func fmt(_ value: Double) -> String {
    value == value.rounded() ? String(Int(value)) : String(value)
}

/// One sheet design: the paper, its title line and setlist lines, and the gaffer tape.
struct SheetArt {
    let sheet: Box
    let title: Box?
    let lines: [Box]
    let tape: Box

    var sheetLayer: [Box] {
        [sheet] + (title.map { [$0] } ?? []) + lines
    }
}

/// Full-size art (brand.md section 4). `light` swaps to the light variant's colours.
func standardArt(light: Bool) -> SheetArt {
    let lineFill = light ? Palette.lineGreyLight : Palette.lineGrey
    let lines = zip([44.0, 53, 62, 71], [30.0, 26, 32, 22]).map { y, width in
        Box(x: 34, y: y, width: width, height: 3, radius: 1.5, fill: lineFill)
    }
    return SheetArt(
        sheet: Box(
            x: 27, y: 20, width: 46, height: 64, radius: 3,
            fill: light ? Palette.ink : Palette.paper,
        ),
        title: Box(
            x: 34, y: 32, width: 24, height: 5, radius: 2,
            fill: light ? Palette.paper : Palette.ink,
        ),
        lines: lines,
        tape: Box(x: 37, y: 14, width: 26, height: 11, radius: 1, fill: Palette.cue),
    )
}

/// 32 px: three setlist lines 5 units thick (title kept), wider tape.
let art32 = SheetArt(
    sheet: Box(x: 27, y: 20, width: 46, height: 64, radius: 3, fill: Palette.paper),
    title: Box(x: 34, y: 32, width: 24, height: 5, radius: 2, fill: Palette.ink),
    lines: zip([44.0, 55, 66], [30.0, 24, 32]).map { y, width in
        Box(x: 34, y: y, width: width, height: 5, radius: 2.5, fill: Palette.lineGrey)
    },
    tape: Box(x: 36, y: 13, width: 28, height: 12, radius: 1, fill: Palette.cue),
)

/// 16 px: sheet and tape only.
let art16 = SheetArt(
    sheet: Box(x: 25, y: 20, width: 50, height: 66, radius: 3, fill: Palette.paper),
    title: nil,
    lines: [],
    tape: Box(x: 35, y: 11, width: 30, height: 15, radius: 1, fill: Palette.cue),
)

// MARK: - SVG

let rotation = "rotate(-6 50 52)"

func svgDocument(_ body: [String]) -> String {
    """
    <?xml version="1.0" encoding="UTF-8"?>
    <!-- Generated by scripts/gen-icon.swift from docs/brand.md section 4 - do not edit. -->
    <svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 100 100">
    \(body.map { "  " + $0 }.joined(separator: "\n"))
    </svg>

    """
}

func rotatedGroup(_ boxes: [Box]) -> [String] {
    ["<g transform=\"\(rotation)\">"] + boxes.map { "  " + $0.svg } + ["</g>"]
}

/// A flat composite: squircle-ish ground (rx 23) plus the rotated sheet and tape.
func composite(_ art: SheetArt, ground: String) -> String {
    svgDocument(
        ["<rect width=\"100\" height=\"100\" rx=\"23\" fill=\"\(ground)\"/>"]
            + rotatedGroup(art.sheetLayer + [art.tape]),
    )
}

// MARK: - Icon Composer document

/// "#RRGGBB" as Icon Composer's "srgb:r,g,b,a" with five decimals.
func iconColor(_ hex: String) -> String {
    let value = UInt32(hex.dropFirst(), radix: 16) ?? 0
    let channels = [value >> 16 & 0xFF, value >> 8 & 0xFF, value & 0xFF]
        .map { String(format: "%.5f", Double($0) / 255) }
    return "srgb:" + channels.joined(separator: ",") + ",1.00000"
}

/// Groups are listed front to back: tape, then the sheet; the fill is the background.
/// In tinted renditions the tape is forced to black so it stays distinct from the sheet by
/// lightness (the system tint otherwise maps the coral close to the sheet and ground).
let iconJSON = """
{
  "fill" : {
    "solid" : "\(iconColor(Palette.ink))"
  },
  "groups" : [
    {
      "layers" : [
        {
          "fill-specializations" : [
            {
              "appearance" : "tinted",
              "value" : {
                "solid" : "gray:0.00000,1.00000"
              }
            }
          ],
          "glass" : true,
          "image-name" : "tape.svg",
          "name" : "tape"
        }
      ],
      "name" : "Tape",
      "shadow" : {
        "kind" : "neutral",
        "opacity" : 0.5
      },
      "specular" : true,
      "translucency" : {
        "enabled" : false,
        "value" : 0.5
      }
    },
    {
      "layers" : [
        {
          "glass" : false,
          "image-name" : "sheet.svg",
          "name" : "sheet"
        }
      ],
      "name" : "Sheet",
      "shadow" : {
        "kind" : "neutral",
        "opacity" : 0.5
      },
      "specular" : false,
      "translucency" : {
        "enabled" : false,
        "value" : 0.5
      }
    }
  ],
  "supported-platforms" : {
    "squares" : [
      "macOS"
    ]
  }
