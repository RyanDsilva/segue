"""

// MARK: - Output

let repoRoot = URL(fileURLWithPath: CommandLine.arguments[0])
    .resolvingSymlinksInPath()
    .deletingLastPathComponent()
    .deletingLastPathComponent()
let iconDir = repoRoot.appendingPathComponent("design/icon")
let fileManager = FileManager.default

func write(_ contents: String, to path: String) throws {
    let url = iconDir.appendingPathComponent(path)
    try fileManager.createDirectory(
        at: url.deletingLastPathComponent(), withIntermediateDirectories: true,
    )
    try Data(contents.utf8).write(to: url, options: .atomic)
}

let standard = standardArt(light: false)
let backgroundSVG = svgDocument(["<rect width=\"100\" height=\"100\" fill=\"\(Palette.ink)\"/>"])
let sheetSVG = svgDocument(rotatedGroup(standard.sheetLayer))
let tapeSVG = svgDocument(rotatedGroup([standard.tape]))

let files: [(String, String)] = [
    ("layers/background.svg", backgroundSVG),
    ("layers/sheet.svg", sheetSVG),
    ("layers/tape.svg", tapeSVG),
    ("master.svg", composite(standard, ground: Palette.ink)),
    ("master-light.svg", composite(standardArt(light: true), ground: Palette.lightGround)),
    ("icon-32.svg", composite(art32, ground: Palette.ink)),
    ("icon-16.svg", composite(art16, ground: Palette.ink)),
    ("Segue.icon/icon.json", iconJSON),
    ("Segue.icon/Assets/sheet.svg", sheetSVG),
    ("Segue.icon/Assets/tape.svg", tapeSVG),
]

// MARK: - Previews

let ictool = "/Applications/Xcode.app/Contents/Applications/Icon Composer.app/Contents/"
    + "Executables/ictool"

@discardableResult
func run(_ tool: String, _ arguments: [String]) throws -> Int32 {
    let process = Process()
    process.executableURL = URL(fileURLWithPath: tool)
    process.arguments = arguments
    process.standardOutput = FileHandle.nullDevice
    try process.run()
    process.waitUntilExit()
    return process.terminationStatus
}

/// Renders a flat SVG at `pixels` square, then upscales nearest-neighbour by `zoom` so
/// small sizes can be inspected pixel by pixel.
func renderSVG(_ svg: String, pixels: Int, zoom: Int, to url: URL) throws {
    guard let image = NSImage(data: Data(svg.utf8)) else {
        throw NSError(domain: "gen-icon", code: 1, userInfo: [
            NSLocalizedDescriptionKey: "AppKit could not load SVG for \(url.lastPathComponent)",
        ])
    }
    func bitmap(_ side: Int) -> NSBitmapImageRep? {
        NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: side, pixelsHigh: side, bitsPerSample: 8,
            samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
            bytesPerRow: 0, bitsPerPixel: 0,
        )
    }
    guard let small = bitmap(pixels), let large = bitmap(pixels * zoom) else { return }
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: small)
    image.draw(in: NSRect(x: 0, y: 0, width: pixels, height: pixels))
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: large)
    NSGraphicsContext.current?.imageInterpolation = .none
    small.draw(in: NSRect(x: 0, y: 0, width: pixels * zoom, height: pixels * zoom))
    NSGraphicsContext.restoreGraphicsState()
    try large.representation(using: .png, properties: [:])?.write(to: url)
}

func renderPreviews() throws {
    let previews = iconDir.appendingPathComponent("previews")
    try fileManager.createDirectory(at: previews, withIntermediateDirectories: true)
    let document = iconDir.appendingPathComponent("Segue.icon").path
    let renditions = ["Default", "Dark", "TintedLight", "TintedDark", "ClearLight", "ClearDark"]
    for rendition in renditions {
        let out = previews.appendingPathComponent("icon-\(rendition.lowercased())-1024.png")
        let status = try run(ictool, [
            document, "--export-image", "--output-file", out.path, "--platform", "macOS",
            "--rendition", rendition, "--width", "1024", "--height", "1024", "--scale", "1",
        ])
        guard status == 0 else {
            throw NSError(domain: "gen-icon", code: Int(status), userInfo: [
                NSLocalizedDescriptionKey: "ictool failed for rendition \(rendition)",
            ])
        }
    }
    for size in [16, 32, 64, 128] {
        let out = previews.appendingPathComponent("icon-default-\(size).png")
        try run(ictool, [
            document, "--export-image", "--output-file", out.path, "--platform", "macOS",
            "--rendition", "Default", "--width", "\(size)", "--height", "\(size)", "--scale", "1",
        ])
    }
    try renderSVG(
        composite(standard, ground: Palette.ink), pixels: 512, zoom: 1,
        to: previews.appendingPathComponent("flat-master-512.png"),
    )
    try renderSVG(
        composite(standardArt(light: true), ground: Palette.lightGround), pixels: 512, zoom: 1,
        to: previews.appendingPathComponent("flat-master-light-512.png"),
    )
    for (art, size) in [(art32, 32), (art16, 16), (standard, 32), (standard, 16)] {
        let tuned = art.tape.width != standard.tape.width
        let name = "flat-\(tuned ? "tuned" : "scaled")-\(size)-x8.png"
        try renderSVG(
            composite(art, ground: Palette.ink), pixels: size, zoom: 8,
            to: previews.appendingPathComponent(name),
        )
    }
}

do {
    if CommandLine.arguments.contains("--check") {
        let stale = files.filter { path, contents in
            let url = iconDir.appendingPathComponent(path)
            return (try? String(contentsOf: url, encoding: .utf8)) != contents
        }.map(\.0)
        guard stale.isEmpty else {
            let list = stale.map { "  design/icon/\($0)" }.joined(separator: "\n")
            FileHandle.standardError.write(Data(
                "error: generated icon files are stale; run `make icon`:\n\(list)\n".utf8,
            ))
            exit(1)
        }
        print("gen-icon: up to date (\(files.count) files)")
        exit(0)
    }
    for (path, contents) in files {
        try write(contents, to: path)
    }
    print("gen-icon: wrote \(files.count) files to design/icon")
    if !CommandLine.arguments.contains("--no-previews") {
        try renderPreviews()
        print("gen-icon: rendered previews to design/icon/previews")
    }
} catch {
    FileHandle.standardError.write(Data("error: gen-icon: \(error)\n".utf8))
    exit(1)
}
